  shuffleAnswers(correctStr, wrongs) {
    const uniqueWrongs = [];
    for (const w of wrongs) {
      const s = String(w);
      if (s !== String(correctStr) && !uniqueWrongs.includes(s)) {
        uniqueWrongs.push(s);
      }
    }
    while (uniqueWrongs.length < 3) {
      const fallback = (parseFloat(correctStr) || 10) + uniqueWrongs.length + 2;
      uniqueWrongs.push(String(fallback));
    }
    const all = [String(correctStr), ...uniqueWrongs.slice(0, 3)];
    // Shuffle
    for (let i = all.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [all[i], all[j]] = [all[j], all[i]];
    }
    return {
      answers: all,
      correct: all.indexOf(String(correctStr))
    };
  },

