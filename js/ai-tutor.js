/* ===================== 3. ДЕРЕКТЕРДІ ЖӘНЕ БЕЙІМДЕУ ТАРИХЫН САҚТАУ ===================== */

function getSmartMathLogs() {
  try {
    const raw = localStorage.getItem('smartmath_research_logs_v1');
    if (raw) return JSON.parse(raw);
  } catch (e) {}
  return {
    attempts: [], // { timestamp, taskId, moduleId, level, skill, isCorrect, errorCode, helpLevelUsed, independentAfterHelp }
    diagnostics: {
      preScore: null,
      postScore: null,
      retentionScore: null,
      history: []
    },
    lastHelpUsedOnSkill: {} // skill -> helpLevelUsed (келесі есепті көмексіз шығаруын бақылау үшін)
  };
}

function saveSmartMathLogs(logs) {
  localStorage.setItem('smartmath_research_logs_v1', JSON.stringify(logs));
}

function recordTaskAttempt(task, chosenIdx, isCorrect, helpLevelUsed) {
  const logs = getSmartMathLogs();
  const errKey = isCorrect ? 'NONE' : ((task.errorMap && task.errorMap[chosenIdx]) || 'APPLY');
  const prevHelp = logs.lastHelpUsedOnSkill[task.skill] || 0;
  const independentAfterHelp = (prevHelp > 0 && helpLevelUsed === 0 && isCorrect);

  logs.attempts.push({
    timestamp: new Date().toISOString(),
    taskId: task.id || 'GEN',
    moduleId: task.moduleId || 1,
    level: task.level || 2,
    skill: task.skill || task.topic || 'Алгебра',
    isCorrect,
    errorCode: errKey,
    helpLevelUsed: helpLevelUsed || 0,
     prevHelpLevel: prevHelp,
    independentAfterHelp
  });

  // Егер осы есепте көмек алса немесе қателессе, келесі есепте көмексіз орындауын тексеру үшін сақтаймыз
  logs.lastHelpUsedOnSkill[task.skill] = isCorrect ? (helpLevelUsed || 0) : Math.max(1, helpLevelUsed || 1);
  saveSmartMathLogs(logs);
}

/* ===================== 4. БЕЙІМДЕУ АЛГОРИТМІ (ADAPTIVE TASK SELECTOR) ===================== */

const AdaptiveEngine = {
  // Оқушының қазіргі қателері мен көмек деңгейіне қарай келесі оңтайлы тапсырмалар тізбегін құрастыру
  selectAdaptiveTasks(moduleId, count = 8) {
    const logs = getSmartMathLogs();
    const pool = VERIFIED_60_TASKS.filter(t => !moduleId || t.moduleId === moduleId);
    const recent = logs.attempts.filter(a => !moduleId || a.moduleId === moduleId).slice(-10);

    // Оқушының ағымдағы бейімделген деңгейін есептеу (1, 2 немесе 3)
    let targetLevel = 1;
    if (recent.length >= 2) {
      const lastTwo = recent.slice(-2);
      const bothIndependentCorrect = lastTwo.every(a => a.isCorrect && a.helpLevelUsed === 0);
      const anyWrong = lastTwo.some(a => !a.isCorrect);
      const lastLvl = lastTwo[lastTwo.length - 1].level || 1;
      if (bothIndependentCorrect) targetLevel = Math.min(3, lastLvl + 1);
      else if (anyWrong) targetLevel = Math.max(1, lastLvl);
      else targetLevel = lastLvl;
    }

    // Олқылығы бар дағдыларды (қате жіберген немесе көмек алған) бірінші кезекте қосу
    const weakSkills = new Set(
      recent.filter(a => !a.isCorrect || a.helpLevelUsed > 0).map(a => a.skill)
    );

    const prioritized = [...pool].sort((a, b) => {
      const aWeak = weakSkills.has(a.skill) ? 1 : 0;
      const bWeak = weakSkills.has(b.skill) ? 1 : 0;
      if (aWeak !== bWeak) return bWeak - aWeak;
      return Math.abs(a.level - targetLevel) - Math.abs(b.level - targetLevel);
    });

    return prioritized.slice(0, count);
  }
};


