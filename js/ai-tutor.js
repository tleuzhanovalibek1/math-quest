  function cloneAndShuffleQuestion(q) {
    const copy = { ...q, answers: [...q.answers] };
    const correctVal = copy.answers[copy.correct];
    for (let i = copy.answers.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [copy.answers[i], copy.answers[j]] = [copy.answers[j], copy.answers[i]];
    }
    copy.correct = copy.answers.indexOf(correctVal);
    return copy;
  }

